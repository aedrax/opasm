@dataclass(frozen=True)
class ArchConfig:
    """Immutable configuration for a CPU architecture.

    Parameters:
        name: Architecture identifier (e.g., "x86", "arm64").
        uc_arch: Unicorn architecture constant.
        uc_mode: Unicorn mode constant.
        cs_arch: Capstone architecture constant.
        cs_mode: Capstone mode constant.
        ks_arch: Keystone architecture constant.
        ks_mode: Keystone mode constant.
        is_little_endian: True if the architecture uses little-endian byte order.
        registers: Mapping of register name strings to engine constant integers.
        instruction_pointer_register: Engine constant for the instruction pointer.
        stack_pointer_register: Engine constant for the stack pointer.
        stack_base: Base address for the stack memory region.
        code_base: Base address for the code memory region.
        data_base: Base address for the data memory region.
        word_size: Architecture word size in bytes (4 or 8).
    """

    name: str
    uc_arch: int
    uc_mode: int
    cs_arch: int
    cs_mode: int
    ks_arch: int
    ks_mode: int
    is_little_endian: bool
    registers: Dict[str, int]
    instruction_pointer_register: int
    stack_pointer_register: int
    stack_base: int
    code_base: int
    data_base: int
    word_size: int


