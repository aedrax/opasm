def get_architecture(name: str) -> ArchConfig:
    """Retrieve an ArchConfig by architecture name.

    Parameters:
        name: Architecture identifier (e.g., "x86", "arm64", "ppc32").

    Returns:
        The ArchConfig for the requested architecture.

    Raises:
        KeyError: If the architecture name is not in the registry.
    """
    return ARCHITECTURES[name]


def list_architectures() -> List[str]:
    """Return a sorted list of all supported architecture names.

    Returns:
        Sorted list of architecture name strings.
    """
    return sorted(ARCHITECTURES.keys())
